"""CF-347: policy and bounded deploy-key registry evidence, not node admission proof.

The deployed layer checks mode/config rather than project binding
(scripts/project-node.sh:1018-1045); deploy_key.py:311-334 checks name and host.
"""

import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
CHECKER = ROOT / "scripts" / "deploy_key.py"


class CredentialLaw(unittest.TestCase):
    def test_policy_requires_foreign_scope_refusal(self):
        text = (ROOT / "specs" / "NODE.md").read_text(encoding="utf-8")
        section = text.split("## Credentials — per-repo deploy keys", 1)[1].split(
            "\n## ", 1
        )[0]
        self.assertIn(
            "it must refuse a credential for\nanother project before use", section
        )
        self.assertIn("refuse unknown or unproven scope", section)
        self.assertIn(
            "real project-binding admission check remains unimplemented", section
        )

    def test_registry_name_refusal_and_same_name_gap(self):
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp)
            keys = home / ".node" / "keys"
            keys.mkdir(parents=True)
            key = keys / "alpha.key"
            key.write_text("fixture, not a credential\n", encoding="utf-8")
            os.chmod(key, 0o600)
            repo_a = "git@forge.example:alpha/alpha.git"
            repo_b = "git@forge.example:beta/beta.git"
            registry = {
                "keys": {
                    "alpha": {
                        "repo": repo_a,
                        "host": "forge.example",
                        "port": 22,
                        "key": str(key),
                    }
                }
            }
            (keys / "keys.json").write_text(json.dumps(registry), encoding="utf-8")
            (keys / "ssh_config").write_text(
                "# generated by scripts/deploy_key.py — one block per host, one identity per repo\n"
                f"Host forge.example\n  IdentitiesOnly yes\n  BatchMode yes\n"
                f"  StrictHostKeyChecking accept-new\n  IdentityFile {key}\n",
                encoding="utf-8",
            )
            os.chmod(keys / "ssh_config", 0o600)

            def check(repo, *extra):
                return subprocess.run(
                    [
                        sys.executable,
                        str(CHECKER),
                        "check",
                        "--home",
                        str(home),
                        "--repo",
                        repo,
                        *extra,
                    ],
                    capture_output=True,
                    text=True,
                    check=False,
                )

            allowed = check(repo_a)
            self.assertEqual(allowed.returncode, 0, allowed.stdout + allowed.stderr)
            foreign = check(repo_b)
            self.assertNotEqual(foreign.returncode, 0)
            self.assertIn("no deploy key registered for beta", foreign.stdout)
            # The real checker does not compare the full repo binding when a name is supplied.
            gap = check(repo_b, "--name", "alpha")
            self.assertEqual(gap.returncode, 0, gap.stdout + gap.stderr)


if __name__ == "__main__":
    unittest.main()
