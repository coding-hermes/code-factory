"""CF-347: policy and deploy-key admission binding evidence."""

import hashlib
import json
import os
from pathlib import Path
import subprocess
import shutil
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
CHECKER = ROOT / "scripts" / "deploy_key.py"


class CredentialLaw(unittest.TestCase):
    def test_policy_requires_foreign_scope_refusal(self):
        text = (ROOT / "specs" / "NODE.md").read_text(encoding="utf-8")
        section = text.split("## Credentials — per-repo deploy keys", 1)[1].split(
            "\n## ", 1
        )[0]
        self.assertIn(
            "it must refuse a credential for\nanother project before use", section
        )
        self.assertIn("refuse unknown or unproven scope", section)

    def test_registry_name_refusal_and_foreign_scope_refusal(self):
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp)
            keys = home / ".node" / "keys"
            keys.mkdir(parents=True)
            key = keys / "alpha.key"
            key.write_text("fixture, not a credential\n", encoding="utf-8")
            os.chmod(key, 0o600)
            repo_a = "git@forge.example:alpha/alpha.git"
            repo_b = "git@forge.example:beta/beta.git"
            registry = {
                "keys": {
                    "alpha": {
                        "repo": repo_a,
                        "host": "forge.example",
                        "port": 22,
                        "key": str(key),
                        "sha256": hashlib.sha256(key.read_bytes()).hexdigest(),
                    }
                }
            }
            (keys / "keys.json").write_text(json.dumps(registry), encoding="utf-8")
            (keys / "ssh_config").write_text(
                "# generated by scripts/deploy_key.py — one block per host, one identity per repo\n"
                f"Host forge.example\n  IdentitiesOnly yes\n  BatchMode yes\n"
                f"  StrictHostKeyChecking accept-new\n  IdentityFile {key}\n",
                encoding="utf-8",
            )
            os.chmod(keys / "ssh_config", 0o600)

            def check(repo, *extra):
                return subprocess.run(
                    [
                        sys.executable,
                        str(CHECKER),
                        "check",
                        "--home",
                        str(home),
                        "--repo",
                        repo,
                        *extra,
                    ],
                    capture_output=True,
                    text=True,
                    check=False,
                )

            allowed = check(repo_a)
            self.assertEqual(allowed.returncode, 0, allowed.stdout + allowed.stderr)
            foreign = check(repo_b)
            self.assertNotEqual(foreign.returncode, 0)
            self.assertIn("no deploy key registered for beta", foreign.stdout)
            foreign = check(repo_b, "--name", "alpha")
            self.assertEqual(foreign.returncode, 1, foreign.stdout + foreign.stderr)
            self.assertIn(
                "FAIL  key — alpha repository binding mismatch", foreign.stdout
            )
            node = subprocess.run(
                [
                    "bash",
                    str(ROOT / "scripts" / "project-node.sh"),
                    "--apply",
                    "--project",
                    "alpha",
                    "--repo",
                    repo_b,
                    "--layers",
                    "40",
                ],
                env={**os.environ, "HOME": str(home), "NODE_DEPLOY_KEY": str(key)},
                capture_output=True,
                text=True,
                check=False,
            )
            self.assertEqual(node.returncode, 1, node.stdout + node.stderr)
            self.assertIn("repository binding mismatch", node.stdout)
            self.assertIn(
                "not attempted — the declared deploy key is unusable", node.stdout
            )
            self.assertFalse((home / "repo").exists())
            del registry["keys"]["alpha"]["repo"]
            (keys / "keys.json").write_text(json.dumps(registry), encoding="utf-8")
            unproven = check(repo_a, "--name", "alpha")
            self.assertEqual(unproven.returncode, 1)
            self.assertIn("unproven repository binding", unproven.stdout)

    @unittest.skipUnless(shutil.which("ssh-keygen"), "ssh-keygen unavailable")
    def test_installed_real_key_binding_and_tamper_refusal(self):
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp) / "home"
            home.mkdir()
            source = Path(tmp) / "fixture"
            subprocess.run(
                ["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(source)],
                check=True,
                capture_output=True,
            )
            repo_a = "git@forge.example:alpha/alpha.git"
            repo_b = "git@forge.example:beta/beta.git"

            def run(*args):
                return subprocess.run(
                    [sys.executable, str(CHECKER), *args],
                    capture_output=True,
                    text=True,
                    check=False,
                )

            installed = run(
                "install",
                "--home",
                str(home),
                "--repo",
                repo_a,
                "--key",
                str(source),
                "--name",
                "alpha",
            )
            self.assertEqual(
                installed.returncode, 0, installed.stdout + installed.stderr
            )
            registered = json.loads((home / ".node/keys/keys.json").read_text())[
                "keys"
            ]["alpha"]
            self.assertEqual(registered["repo"], repo_a)
            self.assertEqual(
                registered["sha256"], hashlib.sha256(source.read_bytes()).hexdigest()
            )
            foreign = run(
                "check", "--home", str(home), "--repo", repo_b, "--name", "alpha"
            )
            self.assertEqual(foreign.returncode, 1)
            self.assertIn("repository binding mismatch", foreign.stdout)
            rebind = run(
                "install",
                "--home",
                str(home),
                "--repo",
                repo_b,
                "--key",
                str(source),
                "--name",
                "alpha",
            )
            self.assertEqual(rebind.returncode, 1)
            self.assertIn("repository binding mismatch", rebind.stdout)
            reuse = run(
                "install",
                "--home",
                str(home),
                "--repo",
                repo_b,
                "--key",
                str(source),
                "--name",
                "beta",
            )
            self.assertEqual(reuse.returncode, 1)
            self.assertIn("credential already registered", reuse.stdout)
            key = home / ".node/keys/alpha.key"
            key.write_text("tampered fixture\n")
            tampered = run(
                "check", "--home", str(home), "--repo", repo_a, "--name", "alpha"
            )
            self.assertEqual(tampered.returncode, 1)
            self.assertIn("unproven credential binding", tampered.stdout)


if __name__ == "__main__":
    unittest.main()
